package me.chaddtheman.mymenu.listener;

import me.chaddtheman.mymenu.render.MenuHolder;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.inventory.InventoryDragEvent;

/**
 * A drag that starts in the player's inventory can end in the menu, so like clicks, every drag
 * while a menu is open is cancelled rather than only those that touch the top half.
 */
public final class InventoryDragListener implements Listener {

    @EventHandler(priority = EventPriority.LOWEST)
    public void onDrag(InventoryDragEvent event) {
        if (event.getView().getTopInventory().getHolder() instanceof MenuHolder) {
            event.setCancelled(true);
        }
    }
}
